#!/bin/sh
# Vendors libjpeg-turbo into Packages/DexCore/Sources/CJPEGTurbo for
# lossless JPEG transforms (crop, rotate, optimise) via transupp.
# Re-run to update: bump VERSION and SHA256 (from a signature-verified download).
set -eu

VERSION=3.2.0
VERSION_NUMBER=3002000
SHA256=6f30092cef9fb839779646608f4ee14ae3cbac989c47fa05e841b0841f09878e
URL="https://github.com/libjpeg-turbo/libjpeg-turbo/releases/download/$VERSION/libjpeg-turbo-$VERSION.tar.gz"

ROOT=$(cd "$(dirname "$0")/.." && pwd)
DEST="$ROOT/Packages/DexCore/Sources/CJPEGTurbo"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

curl -sSfL "$URL" -o "$WORK/ljt.tar.gz"
echo "$SHA256  $WORK/ljt.tar.gz" | shasum -a 256 -c -
tar xzf "$WORK/ljt.tar.gz" -C "$WORK"
SRC="$WORK/libjpeg-turbo-$VERSION"

rm -rf "$DEST/libjpeg" "$DEST/config"
mkdir -p "$DEST/libjpeg/wrapper" "$DEST/config"

# The JPEG library itself plus transupp. Command-line tools, TurboJPEG,
# test programs and SIMD are left out: lossless transforms work on
# compressed coefficients, and ImageIO does all pixel decoding.
for f in "$SRC"/src/j*.c "$SRC"/src/j*.h "$SRC"/src/transupp.c "$SRC"/src/transupp.h; do
    case "$(basename "$f")" in
        jcstest.c|jpegtran.c|jdatadst-tj.c|jdatasrc-tj.c) continue ;;
    esac
    cp "$f" "$DEST/libjpeg/"
done
# 8/12/16-bit variants: each wrapper #includes its base file with a
# different BITS_IN_JSAMPLE, so the base files are excluded from direct
# compilation in Package.swift.
for f in "$SRC"/src/wrapper/j*.c; do cp "$f" "$DEST/libjpeg/wrapper/"; done
rm -f "$DEST/libjpeg/"*.in

cat > "$DEST/config/jconfig.h" <<CONFIG
/* Generated by scripts/vendor-libjpeg-turbo.sh (replaces CMake's jconfig.h). */
#define JPEG_LIB_VERSION  62
#define LIBJPEG_TURBO_VERSION  $VERSION
#define LIBJPEG_TURBO_VERSION_NUMBER  $VERSION_NUMBER
#define C_ARITH_CODING_SUPPORTED 1
#define D_ARITH_CODING_SUPPORTED 1
#define MEM_SRCDST_SUPPORTED  1
#ifndef BITS_IN_JSAMPLE
#define BITS_IN_JSAMPLE  8
#endif
CONFIG

cat > "$DEST/config/jconfigint.h" <<CONFIG
/* Generated by scripts/vendor-libjpeg-turbo.sh (replaces CMake's jconfigint.h). */
#define BUILD  "dex"
#define HIDDEN  __attribute__((visibility("hidden")))
#undef inline
#define INLINE  __inline__ __attribute__((always_inline))
#define THREAD_LOCAL  __thread
#define PACKAGE_NAME  "libjpeg-turbo"
#define VERSION  "$VERSION"
#define SIZEOF_SIZE_T  8
#define HAVE_BUILTIN_CTZL
#if defined(__has_attribute)
#if __has_attribute(fallthrough)
#define FALLTHROUGH  __attribute__((fallthrough));
#else
#define FALLTHROUGH
#endif
#else
#define FALLTHROUGH
#endif
#ifndef BITS_IN_JSAMPLE
#define BITS_IN_JSAMPLE  8
#endif
#undef C_ARITH_CODING_SUPPORTED
#undef D_ARITH_CODING_SUPPORTED
#undef WITH_SIMD
#if BITS_IN_JSAMPLE == 8
#define C_ARITH_CODING_SUPPORTED 1
#define D_ARITH_CODING_SUPPORTED 1
#endif
CONFIG

sed -e "s/@COPYRIGHT_YEAR@/1991-2026/" "$SRC/src/jversion.h.in" > "$DEST/config/jversion.h"

cp "$SRC/LICENSE.md" "$DEST/LICENSE.md"
cp "$SRC/README.ijg" "$DEST/README.ijg"
echo "libjpeg-turbo $VERSION ($SHA256), vendored by scripts/vendor-libjpeg-turbo.sh" > "$DEST/VERSION"
# Shown in the app's About window.
mkdir -p "$ROOT/App/Resources/Licenses"
cp "$SRC/LICENSE.md" "$ROOT/App/Resources/Licenses/libjpeg-turbo-LICENSE.txt"
cp "$SRC/README.ijg" "$ROOT/App/Resources/Licenses/libjpeg-turbo-README-IJG.txt"
echo "Vendored libjpeg-turbo $VERSION into $DEST"
